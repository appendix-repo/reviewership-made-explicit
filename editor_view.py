"""Build the editor view and the author view of an assisted review from the provenance trace (appendix Sections 2.5, 6.7).

Usage: python3 editor_view.py --events runs/provenance_events.json --final runs/12_reviewer_dispositions_final_review.md
                              --origin runs/14_machine_origin.json --out runs/14_editor_view.md
The final-review file must contain a fenced ```json block with a top-level "Dispositions" list, and the signed review
between <!-- SIGNED REVIEW START --> and <!-- SIGNED REVIEW END -->.
"""
import argparse, collections, hashlib, json, re

ap = argparse.ArgumentParser()
for k in ("--events", "--final", "--origin", "--out"):
    ap.add_argument(k, required=True)
a = ap.parse_args()

ev = json.load(open(a.events))
# 1. Integrity of the chain
prev, ok = "0" * 64, True
for e in ev:
    body = {k: v for k, v in e.items() if k != "hash"}
    h = hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest()
    ok = ok and e["prevHash"] == prev and h == e["hash"]
    prev = e["hash"]
kinds = collections.Counter(e["timestampKind"] for e in ev)

# Events of the study's pilot and scoring belong to the research record, not to this review
inrev = lambda e: e["action"] != "score" and not e["actor"]["name"].startswith(("Base-model pilot", "Blind pilot scorer", "Recovery scorer"))
excluded = [e["@id"] for e in ev if not inrev(e)]

# 2. Capabilities used, from the actions recorded
CAP = {"elicit": "Best-Self reviewer (elicitation, Modes E and S)", "specify": "Best-Self reviewer (standards specification)",
       "simulate": "Simulated reviewers", "synthesize": "Panel synthesis", "probe": "Adversarial probes",
       "check": "Check harness", "consistency-check": "Best-Self reviewer (consistency check, Mode C)"}
used = collections.OrderedDict()
for e in ev:
    if e["action"] in CAP and inrev(e):
        used.setdefault(CAP[e["action"]], []).append(e["@id"])
models = sorted({(e["actor"].get("model", "n/a"), e["actor"].get("instructionSetVersion", "n/a")) for e in ev if e["actor"]["kind"] == "agent" and inrev(e)})
humans = sorted({e["actor"]["name"] for e in ev if e["actor"]["kind"] in ("human", "stand-in")})

# 3. Dispositions and composition
txt = open(a.final).read()
disp = None
for blk in re.findall(r"```json\s*(.*?)```", txt, flags=re.S):
    try:
        j = json.loads(blk)
    except json.JSONDecodeError:
        continue
    if isinstance(j, dict) and "Dispositions" in j:
        disp = j["Dispositions"]; break
if disp is None:
    raise SystemExit("No Dispositions block found in " + a.final)
dc = collections.Counter(d.get("decision", "?") for d in disp)
org = json.load(open(a.origin))
s = org["summary"]

L = ["# Editor view of the assisted review (Run 14)", "",
     "*Generated by `tools/editor_view.py` from the provenance trace, the reviewer's dispositions and the machine-origin analysis. "
     "In this demonstration the reviewer and the editor are Claude stand-ins (appendix Section 4.0).*", "",
     "## Record integrity", "",
     f"- Events in the trace: {len(ev)} ({kinds.get('actual', 0)} with actual times, {kinds.get('reconstructed', 0)} reconstructed from file save times).",
     f"- Hash chain: {'verified' if ok else 'BROKEN'} (each event's SHA-256 recomputed over its canonical JSON and linked to its predecessor).",
     f"- Events of the study's pilot and scoring, not part of this review, excluded below: {', '.join(excluded) or 'none'}.", "",
     "## Capabilities used", ""]
for c, ids in used.items():
    L.append(f"- {c}: events {', '.join(ids)}")
L += ["", "## Models and instruction sets", ""] + [f"- {m}; instruction set {i}" for m, i in models]
L += ["", "## Human (stand-in) participants", ""] + [f"- {h}" for h in humans]
L += ["", "## Findings the reviewer consulted, and what the reviewer decided", "",
      f"{len(disp)} dispositions: " + ", ".join(f"{v} {k}" for k, v in dc.most_common()) + ".", "",
      "| Finding | Source | Decision | Reason | Where it lands in the signed review |", "|---|---|---|---|---|"]
for d in disp:
    cell = lambda x: str(x if x is not None else "").replace("|", "/").replace("\n", " ")
    L.append(f"| {cell(d.get('finding'))} | {cell(d.get('source'))} | {cell(d.get('decision'))} | {cell(d.get('reason'))} | {cell(d.get('landsIn'))} |")
land = collections.OrderedDict()
for d in disp:
    if d.get("decision") not in ("accept", "modify"): continue
    for part in re.split(r";\s*", str(d.get("landsIn") or "")):
        part = part.strip()
        if part: land.setdefault(part, collections.Counter())[d["decision"]] += 1
L += ["", "## Where the accepted and modified findings land", "",
      "| Part of the signed review | Accepted | Modified |", "|---|---|---|"]
L += [f"| {k} | {v['accept']} | {v['modify']} |" for k, v in sorted(land.items(), key=lambda kv: -sum(kv[1].values()))]
L += ["", "## Composition of the signed review", "",
      "*This measure compares wording, not content: a finding the reviewer accepted and rewrote in their own words counts as new text. "
      "The dispositions above record where the review's content came from.*", "",
      f"Sentences scored: {s['sentences_scored']}. Threshold: {s['threshold']} of a sentence's word 5-grams (excluding 5-grams found in the manuscript).", "",
      "| Origin | Share of sentences |", "|---|---|",
      f"| Carried from the reviewer's unassisted draft | {s['carried_from_draft_share']:.1%} |",
      f"| New, written by the reviewer after the workbench | {s['new_share']:.1%} |",
      f"| Mixed (draft and agent text together above the threshold) | {s['mixed_share']:.1%} |",
      f"| **Machine origin** (agent text above the threshold) | **{s['machine_origin_share']:.1%}** |", "",
      "Passages of machine or mixed origin, with the agent output they most overlap:", ""]
flag = [r for r in org["sentences"] if r["origin"] in ("agent", "mixed")]
L += [f"- [{r['origin']}; agent overlap {r['agent']}; {r['closest_agent_output']}] {r['sentence'][:220]}" for r in flag] or ["- none"]
L += ["", "## Author view (sent with the decision letter)", "",
      "This review was written with a reviewing workbench under the journal's study protocol. The reviewer used: "
      + "; ".join(used) + ". The reviewer attests that they read the manuscript in full before consulting any "
      "workbench output, decided on every workbench finding before it could enter the review, and takes responsibility for every "
      "statement in it.", ""]
open(a.out, "w").write("\n".join(L))
print(a.out, "written;", len(disp), "dispositions; machine-origin share", s["machine_origin_share"])
