"""Run every replication script and write replication/REPLICATION_REPORT.md and replication/results.json.

Usage (from the repository root):  python replication/replicate_all.py
Exit code 0 if no result FAILs; NOTEs do not fail the run.
"""
import datetime
import importlib
import importlib.metadata
import json
import os
import platform
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lib import ROOT  # noqa: E402

MODULES = ["r01_integrity", "r02_checks", "r03_perspectives_panel", "r04_provenance_review", "r05_style_pilot",
           "r06_recovery", "r07_power", "r08_counts"]


def versions():
    v = {"python": platform.python_version()}
    for m in ("numpy", "scipy", "sympy", "statsmodels", "pandas", "jsonschema"):
        try:
            v[m] = importlib.metadata.version(m)
        except importlib.metadata.PackageNotFoundError:
            v[m] = "not installed"
    return v


def cell(x):
    s = x if isinstance(x, str) else json.dumps(x, ensure_ascii=False)
    s = s.replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= 160 else s[:157] + "…"


def main():
    allr, timing = [], {}
    for m in MODULES:
        t0 = time.time()
        print(f"[{m}] …", flush=True)
        res = importlib.import_module(m).run()
        timing[m] = round(time.time() - t0, 1)
        for r in res:
            r.script = f"replication/{m}.py"
        allr += res
        c = {s: sum(r.status == s for r in res) for s in ("PASS", "FAIL", "NOTE")}
        print(f"[{m}] {c['PASS']} pass, {c['FAIL']} fail, {c['NOTE']} note ({timing[m]} s)", flush=True)
    tot = {s: sum(r.status == s for r in allr) for s in ("PASS", "FAIL", "NOTE")}
    v = versions()
    L = ["# Replication report", "",
         f"Generated by `replication/replicate_all.py` on {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M UTC}.", "",
         "Environment: " + ", ".join(f"{k} {x}" for k, x in v.items()) + ".", "",
         f"**{len(allr)} results: {tot['PASS']} PASS, {tot['FAIL']} FAIL, {tot['NOTE']} NOTE.**", "",
         "PASS: the recomputed value equals the value in the technical appendix. FAIL: it does not. "
         "NOTE: reproduced only approximately, or depends on a counting convention the files do not fix (see the detail).", ""]
    for g in dict.fromkeys(r.group for r in allr):
        L += [f"## {g}", "", "| Status | Claim | Appendix § | Appendix value | Recomputed | Script | Detail |", "|---|---|---|---|---|---|---|"]
        for r in allr:
            if r.group == g:
                L.append(f"| {r.status} | {cell(r.claim)} | {r.section} | {cell(r.expected)} | {cell(r.observed)} | "
                         f"`{r.script}` | {cell(r.detail)} |")
        L.append("")
    open(os.path.join(HERE, "REPLICATION_REPORT.md"), "w", encoding="utf-8").write("\n".join(L))
    json.dump({"environment": v, "totals": tot, "seconds": timing,
               "results": [{**r.__dict__, "expected": r.expected, "observed": r.observed} for r in allr]},
              open(os.path.join(HERE, "results.json"), "w"), indent=1, ensure_ascii=False, default=str)
    print(f"\n{len(allr)} results: {tot['PASS']} PASS, {tot['FAIL']} FAIL, {tot['NOTE']} NOTE")
    print("Report: replication/REPLICATION_REPORT.md")
    for r in allr:
        if r.status == "FAIL":
            print("FAIL:", r.claim, "| expected", r.expected, "| got", r.observed, "|", r.detail)
    return 1 if tot["FAIL"] else 0


if __name__ == "__main__":
    os.chdir(ROOT)
    sys.exit(main())
